import Foundation

/// Renders a snapshot as a human-readable Markdown report.
public enum MarkdownExporter {
    public static func render(_ snapshot: Snapshot) -> String {
        var out: [String] = []
        let title = snapshot.label.map { "MacBlueprint — \($0)" } ?? "MacBlueprint snapshot"
        out.append("# \(escape(title))")
        out.append("")
        out.append("| | |")
        out.append("|---|---|")
        out.append("| Created | \(ISO8601DateFormatter().string(from: snapshot.createdAt)) |")
        out.append("| Machine | \(snapshot.machine.model ?? "unknown") (\(snapshot.machine.architecture)) |")
        out.append("| macOS | \(snapshot.machine.osVersion) |")
        out.append("| Generated by | \(snapshot.tool.name) \(snapshot.tool.version) |")
        out.append("")

        out.append(contentsOf: summary(snapshot))
        out.append(contentsOf: apps(snapshot.apps))
        out.append(contentsOf: homebrew(snapshot.homebrew))
        out.append(contentsOf: editors(snapshot.editors))
        out.append(contentsOf: devEnvironment(snapshot.devEnvironment))
        out.append(contentsOf: shell(snapshot.shell))

        if !snapshot.warnings.isEmpty {
            out.append("## Warnings")
            out.append("")
            out.append(contentsOf: snapshot.warnings.map { "- \(escape($0))" })
            out.append("")
        }
        return out.joined(separator: "\n")
    }

    private static func summary(_ s: Snapshot) -> [String] {
        let extensionCount = s.editors.reduce(0) { $0 + $1.extensions.count }
        let count = { (source: AppItem.Source) in s.apps.filter { $0.source == source }.count }
        let installed = s.apps.count - count(.system)
        return [
            "## Summary",
            "",
            "- **\(installed)** apps (\(count(.appStore)) App Store, \(count(.homebrew)) Homebrew, \(count(.manual)) manual) + \(count(.system)) built-in",
            s.homebrew.installed
                ? "- **\(s.homebrew.formulae.filter(\.onRequest).count)** Homebrew formulae, **\(s.homebrew.casks.count)** casks"
                : "- Homebrew not installed",
            "- **\(extensionCount)** editor extensions across \(s.editors.count) editor(s)",
            "- **\(s.devEnvironment.tools.count)** developer tools",
            "",
        ]
    }

    private static func apps(_ apps: [AppItem]) -> [String] {
        guard !apps.isEmpty else { return [] }
        var out = ["## Applications", "", "| App | Version | Source | Bundle ID |", "|---|---|---|---|"]
        for app in apps {
            var source = app.source.rawValue
            if let token = app.caskToken { source += " (`\(token)`)" }
            if let id = app.appStoreId { source += " (id \(id))" }
            out.append("| \(escape(app.name)) | \(app.version ?? "—") | \(source) | \(app.bundleId.map { "`\($0)`" } ?? "—") |")
        }
        out.append("")
        return out
    }

    private static func homebrew(_ brew: BrewInventory) -> [String] {
        guard brew.installed else { return [] }
        var out = ["## Homebrew", "", "Prefix: `\(brew.prefix ?? "unknown")`", ""]
        if !brew.taps.isEmpty {
            out.append("**Taps:** " + brew.taps.map { "`\($0)`" }.joined(separator: ", "))
            out.append("")
        }
        let requested = brew.formulae.filter(\.onRequest)
        if !requested.isEmpty {
            out.append("### Formulae")
            out.append("")
            out.append(contentsOf: requested.map { "- `\($0.name)` \($0.version ?? "")" })
            let dependencies = brew.formulae.count - requested.count
            if dependencies > 0 { out.append("- _…and \(dependencies) dependencies_") }
            out.append("")
        }
        if !brew.casks.isEmpty {
            out.append("### Casks")
            out.append("")
            out.append(contentsOf: brew.casks.map { "- `\($0.token)` \($0.version ?? "")" })
            out.append("")
        }
        return out
    }

    private static func editors(_ editors: [EditorInventory]) -> [String] {
        var out: [String] = []
        for editor in editors {
            out.append("## \(editor.editor.displayName) extensions")
            out.append("")
            if editor.extensions.isEmpty {
                out.append("_No extensions._")
            } else {
                out.append(contentsOf: editor.extensions.map { "- `\($0.id)` \($0.version ?? "")" })
            }
            out.append("")
        }
        return out
    }

    private static func devEnvironment(_ env: DevEnvironment) -> [String] {
        var out = ["## Developer environment", ""]
        out.append("Xcode developer directory: \(env.developerDirectory.map { "`\($0)`" } ?? "not installed")")
        out.append("")
        if !env.tools.isEmpty {
            out.append("| Tool | Version | Installed via |")
            out.append("|---|---|---|")
            out.append(contentsOf: env.tools.map { "| \($0.name) | \($0.version ?? "—") | \($0.manager ?? "—") |" })
            out.append("")
        }
        if !env.versionManagers.isEmpty {
            out.append("**Version managers**")
            out.append("")
            for manager in env.versionManagers {
                let versions = manager.installedVersions.isEmpty ? "no versions installed" : manager.installedVersions.joined(separator: ", ")
                out.append("- \(manager.name): \(versions)")
            }
            out.append("")
        }
        return out
    }

    private static func shell(_ shell: ShellInfo) -> [String] {
        var out = ["## Shell", ""]
        out.append("- Login shell: \(shell.loginShell.map { "`\($0)`" } ?? "unknown")")
        if !shell.frameworks.isEmpty { out.append("- Frameworks: \(shell.frameworks.joined(separator: ", "))") }
        if let prompt = shell.prompt { out.append("- Prompt: \(prompt)") }
        out.append("")
        return out
    }

    private static func escape(_ text: String) -> String {
        text.replacingOccurrences(of: "|", with: "\\|")
    }
}
